'use strict';
// core/writing/scene-prompt.js
//
// 写作场景群聊的群规则（替换通用群规则，只在首轮与上下文压缩后注入一次）。
//
// 写作在写作 Tab 里完成，群聊是后台（2026-10-01）。Tab 从每位 AI 的回答里取出文章，按 Markdown 排版，
// 每位一个标签页（解析见 core/writing/workbench.js），所以这里只讲一件事：回答怎么分成「文章」和「给田哥的话」。
//
// 2026-10-03 交稿格式从 JSON 卡片改成两行 HTML 注释标记 + 两个固定小标题：10-01 实测三家都没附 JSON 卡片，
// Claude 还把写作说明接在正文末尾。标记在 Markdown 里不显示，群聊里读起来依旧干净。
//
// 文风不在这里：启动成员时作为系统指令装进去（core/writing/voice-pack.js）。这里只留文件路径作后备，
// 群规则越短，首条消息越不容易超过 Codex 长文本输入通道的门槛（见 core/codex-editor-input.js）。
//
// 2026-10-11 田哥定的写法：标题要让人眼前一亮、不附标题候选；缺材料时 AI 直接构造具体的例子和数字，
// 在「给田哥」里列明由他改；三位各自独立写，第二轮起读别人的稿互相借鉴（群聊会把其他成员的整稿
// 作为「新增发言」带给每一位，见 core/group-chat-orchestrator.js 的 buildDelta）。

const path = require('path');
const { writingPaths } = require('./config.js');

function buildWritingScenePrompt(displayName, opts = {}, env = process.env) {
  const paths = writingPaths(env);
  const name = displayName || 'AI';
  return [
    '## 这是写作群聊',
    `你是${name}。田哥是作者，群里几位 AI 各写一版，帮他写成一篇中文文章。田哥在「写作 Tab」里读稿：每位一个标签页，两行标记之间的 Markdown 排成文章，标记之后是你写给田哥的话。`,
    '',
    '## 每轮做什么',
    '- 第一轮：田哥的第一条消息是这篇的中心思想。独立构思，直接写一版完整的稿。只有田哥本人知道、猜错会让整篇白写的事，才在「想问田哥」里问，最多 3 个，每个附推荐答案，稿里先按推荐答案写。',
    '- 之后每一轮：「新增发言」里有其他几位的稿。读完它们，把别人写得比你好的开头、例子、比喻、论证化进自己的稿，同时守住你自己的切入，让几份稿各有各的好；再按田哥的回答和点评改（点评没点到你，就参考他对别人的意见），交完整的新版本。',
    '- 田哥点名某一位汇总定稿：只有那一位写。读完群里所有稿和田哥的全部点评，取各稿之长改定，用定稿标记交稿。',
    '',
    '## 写成什么样',
    '- 标题让人眼前一亮。贴切是底线，在贴切之上尽量标新立异：一个反直觉的判断、一组意外的对照、一句化用得恰到好处的诗文，都胜过四平八稳的概括。小标题同样用心，每个都让读者想往下读。诗文典故只在真正贴切处用，一篇里点到一两处就够。',
    '- 只交一个标题，正文里定下来就好。',
    '- 缺真实材料的地方，按最可能的情况构造具体、可信的例子、场景和数字，直接写成具体的事；构造了哪些，在「给田哥」里逐条列出，田哥会换成真实的。',
    '- 篇幅跟着内容走，技术博客可以写长，每一段都在推进就好。',
    '',
    '## 回答的格式',
    '每次回答都是下面这个样子：',
    '',
    '<!-- 文章开始 -->',
    '# 文章标题',
    '',
    '完整正文（Markdown）……',
    '<!-- 文章结束 -->',
    '',
    '## 给田哥',
    '一两句话说这份稿的切入和取舍；再逐条列出你构造的例子、场景和数字，以及拿不准的事实。',
    '',
    '## 想问田哥',
    '1. 问题',
    '   推荐：你的推荐答案',
    '',
    '- 两行标记之间只放文章本身：从「# 标题」开始，到正文最后一句结束。对田哥说的话、写作思路、待确认的事项都写进「给田哥」。',
    '- 定稿时两行标记换成 <!-- 定稿开始 --> 和 <!-- 定稿结束 -->。',
    '- 没有要问的，「想问田哥」整节省掉。',
    '',
    '## 照田哥的文风写',
    `- 你的系统指令「写作须知」里有田哥的文风指南、范文入口和起草指南，照它写。没看到的话，动笔前读 ${path.join(paths.voiceDir, 'SKILL.md')}、范文 ${path.join(paths.voiceDir, 'exemplars.md')}、起草指南 ${paths.draftGuide}。`,
    '- 引用真实数据和实验结果时，把握程度写进措辞，比如“在这组实验里”“这只是类比”。',
  ].join('\n');
}

module.exports = { buildWritingScenePrompt };
