'use strict';
const assert = require('node:assert/strict');
const fs = require('fs'), os = require('os'), path = require('path'), crypto = require('crypto');
const { ARTWORK_KEYS, validatePack, validateCatalog, validImage, createAppearanceStore } = require('../core/appearance-packs');
const { iconSource } = require('../renderer/appearance-icons');
const tiny = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jS1EAAAAASUVORK5CYII=';
const pack = (id = 'test-cats', version = '1.0.0') => ({ schema: 1, id, version, name: '猫猫', avatars: Object.fromEntries(ARTWORK_KEYS.map(k => [k, tiny])) });
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'hub-appearance-unit-'));
const isolated = id => ({ dataDir: path.join(tmp, id), bundledDir: path.join(tmp, 'empty'), sources: [] });
(async () => {
  assert.equal(validImage(tiny), true);
  for (const input of ['javascript:alert(1)', 'data:image/svg+xml;base64,PHN2Zz4=', 'data:image/png;base64,SGVsbG8=', 'file:///C:/secret.png']) assert.equal(validImage(input), false);
  assert.throws(() => validatePack({ ...pack(), id: '../escape' }));
  for (const id of [undefined, null, ['array-id']]) assert.throws(() => validatePack({ ...pack(), id }));
  assert.throws(() => validatePack({ ...pack(), avatars: { claude: tiny } }));
  const store = createAppearanceStore(isolated('persist'));
  assert.equal(store.snapshot().preferences.pack, 'default');
  store.install(pack()); store.install(pack('test-bots'));
  const custom = store.saveCustom(tiny);
  store.savePreferences({ pack: 'test-cats', overrides: { codex: 'test-bots', claude: custom.id, gemini: 'missing' }, icons: 'mono', iconOverrides: { glm: 'test-bots' } });
  const resumed = createAppearanceStore(isolated('persist')).snapshot();
  assert.equal(resumed.preferences.pack, 'test-cats');
  assert.equal(resumed.preferences.overrides.codex, 'test-bots');
  assert.equal(resumed.preferences.overrides.claude, custom.id);
  assert.equal(resumed.preferences.overrides.gemini, undefined);
  assert.equal(resumed.custom[custom.id], tiny);
  assert.equal(resumed.preferences.iconOverrides.glm, 'test-bots');
  const smallChange = store.savePreferences({ pack: 'test-cats', overrides: {}, icons: 'brand', iconOverrides: {} });
  assert.equal(Object.hasOwn(smallChange, 'packs'), false, 'preference changes do not transfer the full image library');
  assert.ok(JSON.stringify(smallChange).length < 256);
  assert.throws(() => store.install({ ...pack(), avatars: {} }));
  assert.equal(store.snapshot().preferences.pack, 'test-cats', 'invalid installation preserves active preferences');
  assert.equal(store.snapshot().packs.length, 2);
  store.install(pack('test-cats', '2.0.0'));
  assert.throws(() => store.install(pack('test-cats')), /旧版本/);
  assert.equal(store.snapshot().packs.find(p => p.id === 'test-cats').version, '2.0.0');
  assert.equal(createAppearanceStore(isolated('persist')).snapshot().packs.find(p => p.id === 'test-cats').version, '2.0.0');
  const bundledDir = path.join(tmp, 'same-version-bundled'); fs.mkdirSync(bundledDir);
  fs.writeFileSync(path.join(bundledDir, 'test-cats-1.0.0.json'), JSON.stringify(pack()));
  const sameConfig = { ...isolated('same-version'), bundledDir };
  const same = createAppearanceStore(sameConfig);
  same.install({ ...pack(), name: '用户导入的同版本' });
  assert.equal(createAppearanceStore(sameConfig).snapshot().packs[0].name, '用户导入的同版本');
  const invalidImage = 'data:image/png;base64,' + Buffer.from([137,80,78,71,13,10,26,10,0,0,0,0]).toString('base64');
  const decoding = createAppearanceStore({ ...isolated('decoding'), decodeImage: image => { if (image === invalidImage) throw new Error('decode failed'); } });
  decoding.install(pack());
  assert.throws(() => decoding.install({ ...pack(), version: '2.0.0', avatars: Object.fromEntries(ARTWORK_KEYS.map(k => [k, invalidImage])) }), /decode failed|头像/);
  assert.equal(decoding.snapshot().packs[0].version, '1.0.0', 'decode failure preserves installed pack');
  const bytes = Buffer.from(JSON.stringify(pack('downloaded')));
  const entry = { id: 'downloaded', name: '下载测试', version: '1.0.0', file: 'downloaded-1.0.0.json', bytes: bytes.length, sha256: crypto.createHash('sha256').update(bytes).digest('hex') };
  const catalog = { schema: 1, version: '1.0.0', packs: [entry] };
  assert.throws(() => validateCatalog({ ...catalog, packs: [{ ...entry, file: '../payload' }] }));
  assert.throws(() => validateCatalog({ ...catalog, packs: [entry, entry] }));
  const events = [], requests = [];let failCatalog=false;
  const sources = ['broken', 'working'].map(id => ({ id, name: id, manifest: `https://${id}.test/catalog.json`, files: `https://${id}.test/` }));
  const fetchImpl = async url => {
    requests.push(url);
    if(failCatalog && url.endsWith('catalog.json')) return new Response('unavailable',{status:503});
    if (url.includes('broken')) return new Response('<html>blocked</html>', { headers: { 'content-type': 'text/html' } });
    return new Response(url.endsWith('catalog.json') ? JSON.stringify(catalog) : bytes, { headers: { 'content-type': 'application/json' } });
  };
  const download = createAppearanceStore({ ...isolated('download'), sources, fetchImpl, emit: (name, data) => events.push({ name, phase: data.phase }) });
  assert.equal(requests.length, 0, 'startup never contacts download services');
  await download.check();
  assert.equal(download.snapshot().state.phase, 'available');
  await download.download('downloaded');
  assert.equal(download.snapshot().state.phase, 'installed');
  assert.equal(download.snapshot().packs[0].id, 'downloaded');
  assert.equal(download.snapshot().state.attempts.length, 2);
  assert.equal(download.snapshot().preferences.pack, 'default', 'download never silently applies a pack');
  assert.ok(events.some(e => e.phase === 'downloading'));
  failCatalog=true;await download.check();
  assert.equal(download.snapshot().state.phase,'error');
  assert.ok(download.snapshot().state.checks.every(c=>!c.ok));
  assert.deepEqual(download.snapshot().state.attempts,[],'a new catalog check must discard earlier download success');
  assert.equal(download.snapshot().state.progress,null);
  assert.equal(download.snapshot().packs[0].id,'downloaded','failed check retains installed packs');
  const corrupt = createAppearanceStore({ ...isolated('corrupt'), sources: [sources[1]], fetchImpl: async url => new Response(url.endsWith('catalog.json') ? JSON.stringify(catalog) : 'bad', { headers: { 'content-type': 'application/json' } }) });
  await corrupt.check(); await corrupt.download('downloaded');
  assert.equal(corrupt.snapshot().state.phase, 'error');
  assert.equal(corrupt.snapshot().packs.length, 0, 'hash/size failures never install');
  const stalled = createAppearanceStore({ ...isolated('stalled'), sources, catalogBodyTimeoutMs: 60, fetchImpl: async url => url.includes('broken') ? new Response(new ReadableStream({ start() {} })) : new Response(JSON.stringify(catalog), { headers: { 'content-type': 'application/json' } }) });
  const checkStart = Date.now();
  await stalled.check();
  assert.ok(Date.now() - checkStart < 2000, 'a stalled response body does not block the available source');
  assert.equal(stalled.snapshot().state.phase, 'available');
  for (const style of ['round', 'tile', 'mono', 'night']) assert.ok(iconSource('codeagent', style).startsWith('data:image/svg+xml;base64,'));
  assert.equal(iconSource('../private', 'mono'), '');
  console.log('unit-appearance-packs: validation, persistence, custom upload, multi-source download, integrity and default preservation passed');
})().catch(e => { console.error(e); process.exitCode = 1; });
