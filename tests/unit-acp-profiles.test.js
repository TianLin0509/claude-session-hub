'use strict';
const fs=require('fs'),os=require('os'),path=require('path'),assert=require('assert/strict');
const {buildAcpOptions,PLAN_BASE_URL}=require('../core/acp-profiles');
const {imagePaths,validateImages}=require('../core/acp-attachments');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'hub-acp-profile-'));
const entry=path.join(root,'cli.js');fs.writeFileSync(entry,'');
const config={acp:{nodePath:process.execPath,apiKey:'test-private-credential',providers:{qwen:{entryPath:entry,model:'qwen3.8-max'}}}};
const options={id:'one',cwd:root};
const built=buildAcpOptions('qwen',options,config,root,{ZCODE_ACP_RESUME_SESSION:'foreign',DSH_HOME:'foreign',CODEX_HOME:'foreign',OPENAI_API_KEY:'foreign',ANTHROPIC_AUTH_TOKEN:'foreign',NODE_OPTIONS:'foreign',PATH:process.env.PATH});
assert.equal(built.launch.env.OPENAI_BASE_URL,PLAN_BASE_URL);assert.equal(built.launch.env.OPENAI_API_KEY,config.acp.apiKey);
assert.equal(built.launch.env.USERPROFILE,built.home);assert.equal(built.launch.env.PATH,process.env.PATH);
for(const key of ['ZCODE_ACP_RESUME_SESSION','DSH_HOME','CODEX_HOME','ANTHROPIC_AUTH_TOKEN','NODE_OPTIONS'])assert.equal(built.launch.env[key],undefined);
assert(!built.launch.args.join(' ').includes(config.acp.apiKey));
const bridge=path.join(root,'bridge');fs.mkdirSync(bridge);fs.writeFileSync(path.join(bridge,'package.json'),'{}');
config.acp.providers['deepseek-acp']={entryPath:entry,bridgePath:bridge,model:'deepseek-v4-pro'};
const dsh=buildAcpOptions('deepseek-acp',{id:'dsh',cwd:root},config,root,{BAILIAN_TPP_API_KEY:'foreign'});
assert.equal(dsh.launch.env.BAILIAN_TPP_API_KEY,undefined,'native authentication must not shadow a read-only environment key');
assert.equal(dsh.launch.env.BAILIAN_API_KEY,config.acp.apiKey);
assert.equal(dsh.authMeta['api-key'].apiKey,config.acp.apiKey);
const patches=JSON.parse(fs.readFileSync(dsh.launch.args[dsh.launch.args.indexOf('--patch')+1],'utf8'));
assert(patches.find(p=>p.id==='llm-pi-ai').config.providers['bailian-tpp'].models.every(m=>m.compat.supportsDeveloperRole===false),
  'Token Plan system instructions must use the supported system role');
assert(patches.find(p=>p.id==='system-prompt').config.personaSuffix.includes('ask_user_question'));
assert(patches.some(p=>p.id==='acp-plugin'),'behavior patch retains the ACP transport');
// Explicit API selection must work without Token Plan credentials and keep the DSH runtime.
const directConfig={...config,deepseekApiKey:'direct-private-key',acp:{...config.acp,apiKey:'',providers:{'deepseek-acp':{entryPath:entry,bridgePath:bridge,model:'deepseek-v4.1-flash'}}}};
const direct=buildAcpOptions('deepseek-acp',{id:'direct',cwd:root,deepseekRoute:'api',model:'deepseek-v4.1-flash'},directConfig,root,{});
assert.equal(direct.profileId,'deepseek-api:deepseek-acp');
assert.equal(direct.model,'deepseek-flash');
const directLink=path.join(direct.launch.env.DSH_HOME,'profiles/acp/node_modules/@openma/deepseek-harness-acp');
if(process.platform==='win32')fs.rmdirSync(directLink);else fs.unlinkSync(directLink);
assert.equal(direct.launch.env.BAILIAN_API_KEY,'direct-private-key');
const directPatches=JSON.parse(fs.readFileSync(direct.launch.args[direct.launch.args.indexOf('--patch')+1],'utf8'));
assert.equal(directPatches.find(p=>p.id==='llm-pi-ai').config.providers['bailian-tpp'].baseURL,'https://api.deepseek.com/v1');
assert.throws(()=>buildAcpOptions('deepseek-acp',{id:'missing',cwd:root,deepseekRoute:'api'},config,root,{}),/DeepSeek API Key/);
assert.throws(()=>buildAcpOptions('deepseek-acp',{id:'bad-route',cwd:root,deepseekRoute:'bad'},config,root,{}),/消费通道/);
// Remove only the owned fixture link so the suite can safely clean its temp tree.
const bridgeLink=path.join(dsh.launch.env.DSH_HOME,'profiles/acp/node_modules/@openma/deepseek-harness-acp');
assert(path.resolve(bridgeLink).startsWith(path.resolve(root)+path.sep));
assert(fs.lstatSync(bridgeLink).isSymbolicLink());assert.equal(fs.realpathSync(bridgeLink),fs.realpathSync(bridge));
if(process.platform==='win32')fs.rmdirSync(bridgeLink);else fs.unlinkSync(bridgeLink);
assert.throws(()=>buildAcpOptions('qwen',options,{acp:{...config.acp,baseURL:'https://api.deepseek.com/v1'}},root),/端点/);
assert.throws(()=>buildAcpOptions('qwen',{...options,model:'deepseek-official::deepseek-v4-pro'},config,root),/命名空间/);
const mcp=path.join(root,'mcp.json');fs.writeFileSync(mcp,JSON.stringify([{name:'tool',command:'node',args:['server.js'],env:[]}]));
config.acp.providers.qwen.mcpConfigPath=mcp;
assert.equal(buildAcpOptions('qwen',options,config,root).mcpServers[0].name,'tool');
fs.writeFileSync(mcp,'{}');assert.throws(()=>buildAcpOptions('qwen',options,config,root),/数组/);
delete config.acp.providers.qwen.mcpConfigPath;
const outside=fs.mkdtempSync(path.join(os.tmpdir(),'hub-acp-foreign-'));
assert.throws(()=>buildAcpOptions('qwen',{id:'branch',cwd:root,acpFork:{home:outside}},config,root),/分叉目录/);
const file=path.join(root,'sample with spaces.png');fs.writeFileSync(file,Buffer.alloc(16));
assert.deepEqual(imagePaths('看看 "'+file+'"\n"'+file+'"'),[{type:'localImage',path:file}]);
assert.throws(()=>validateImages(imagePaths('"'+file+'"'),'glm-5.2',{promptCapabilities:{image:true}}),/不支持图片/);
assert.throws(()=>validateImages(Array(5).fill({type:'localImage',path:file}),'qwen3.8-max',{promptCapabilities:{image:true}}),/最多/);
assert.doesNotThrow(()=>validateImages([{type:'localImage',path:file}],'qwen3.8-max',{promptCapabilities:{image:true}}));
console.log('ACP profiles: route lock, environment isolation, MCP validation, fork containment and image capabilities PASS');

const forkPlan=require('../core/session-fork-plan').planSessionFork({source:{id:'source',kind:'deepseek-acp',runtimeBackend:'acp',cwd:root,acpSid:'12345678-1234-1234-1234-123456789abc',acpCapabilities:{sessionCapabilities:{fork:true}},deepseekRoute:'api',currentModel:{id:'deepseek-flash'}}});
assert.equal(forkPlan.ok,true);
assert.equal(forkPlan.opts.deepseekRoute,'api');
